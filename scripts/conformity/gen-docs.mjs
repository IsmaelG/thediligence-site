// Generate docs/UI-SPEC.md and docs/pages/<Page>.md from the frozen data (markup, CSS, redlines, behaviour).
//   node scripts/conformity/gen-docs.mjs
// Never edit the outputs: change spec/ and regenerate.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SPEC, readJSON, pagesConfig, parse, isEl, attr, walk, textOf, norm, splitTop, splitSelectors, linkTarget } from './lib.mjs';

const cfg = pagesConfig();
const R = {}; for (const p of cfg.pages) { R[p.name] = {}; for (const w of cfg.widths) R[p.name][w] = readJSON(path.join(SPEC, 'redlines', `${p.name}.${w}.json`)); }
const beh = readJSON(path.join(SPEC, 'behaviour.json'));
const links = readJSON(path.join(SPEC, 'links.json')).rules;
const routeOf = Object.fromEntries(cfg.pages.map((p) => [p.design, p.route]));
const css = Object.fromEntries(cfg.pages.map((p) => [p.name, fs.readFileSync(path.join(SPEC, 'styles', `${p.name}.css`), 'utf8')]));
const overrides = readJSON(path.join(SPEC, 'copy-overrides.json')).overrides;
const seams = readJSON(path.join(SPEC, 'seams.json')).removed;
const hex = (c) => { const m = String(c).match(/rgba?\(([\d.]+), ([\d.]+), ([\d.]+)(?:, ([\d.]+))?\)/); if (!m) return c; const h = '#' + [1, 2, 3].map((i) => Number(m[i]).toString(16).padStart(2, '0')).join('').toUpperCase(); if (m[4] === '0') return 'transparent'; return m[4] !== undefined && m[4] !== '1' ? `${h} @${m[4]}` : h; };
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const today = new Date().toISOString().slice(0, 10);
const head = (title) => `# ${title}\n\nGenerated by \`scripts/conformity/gen-docs.mjs\` from \`spec/\` on ${today}. Do not edit: change \`spec/\` (docs/CONFORMITY.md section 7) and regenerate. Source: ${cfg.source}.\n\n`;

// Markup trees
const trees = Object.fromEntries(cfg.pages.map((p) => [p.name, parse(fs.readFileSync(path.join(SPEC, 'markup', `${p.name}.html`), 'utf8'))]));
const rootOf = (name) => trees[name].childNodes.find(isEl);
const sectionsOf = (name) => rootOf(name).childNodes.filter(isEl);
const classesIn = (node) => { const s = new Set(); walk(node, (n) => { if (isEl(n)) (attr(n, 'class') || '').split(/\s+/).filter(Boolean).forEach((c) => s.add(c)); }); return [...s]; };

// CSS rules flattened: { media, selectors, decl }
function rules(text, media = '') {
  const out = [];
  for (const b of splitTop(text.replace(/\/\*[\s\S]*?\*\//g, ''))) {
    if (b.raw) continue;
    const p = b.prelude.replace(/\s+/g, ' ');
    if (/^@media/.test(p)) out.push(...rules(b.body, p));
    else if (p.startsWith('@')) out.push({ media, selectors: [p], decl: '(at-rule)' });
    else out.push({ media, selectors: splitSelectors(p), decl: b.body.trim().replace(/\s+/g, ' ') });
  }
  return out;
}

// ---------------- UI-SPEC ----------------
let ui = head('UI-SPEC: TheDiligence site, design V5');
ui += `Two pages: ${cfg.pages.map((p) => `**${p.name}** (\`${p.route}\`)`).join(' and ')}. Measured at ${cfg.widths.join(', ')} px in Chromium, light theme, reduced motion. Every number below comes from \`spec/redlines\` or \`spec/styles\`.\n\n`;

ui += `## 1. Frame and grid\n\n`;
const mw = {}; for (const p of cfg.pages) walk(rootOf(p.name), (n) => { if (!isEl(n)) return; const m = (attr(n, 'style') || '').match(/max-width: ([^;]+)/); if (m) mw[m[1]] = (mw[m[1]] || 0) + 1; });
ui += `- **Page root**: \`<div data-page="<Page>">\` with Overpass, ink \`#14161A\` and paper \`#F5F3EE\` inline; the body has \`margin: 0\` and the paper background (\`spec/styles/*.css\`, first rule).\n`;
ui += `- **Containers** (inline \`max-width\`, count across both pages): ${Object.entries(mw).sort((a, b) => b[1] - a[1]).map(([k, v]) => `\`${k}\` ×${v}`).join(', ')}. Content columns are \`max-width: 1200px; margin: 0 auto\`.\n`;
const pads = {}; for (const p of cfg.pages) walk(rootOf(p.name), (n) => { if (!isEl(n) || !(attr(n, 'class') || '').split(/\s+/).includes('sec')) return; const m = (attr(n, 'style') || '').match(/(?:^|; )padding: ([^;]+)/); if (m) (pads[m[1]] ||= []).push(`${p.name} ${n.tagName}`); });
ui += `- **Sections** (class \`.sec\`) carry their padding inline: ${Object.entries(pads).map(([k, v]) => `\`${k}\` (${v.length}: ${[...new Set(v)].join(', ')})`).join('; ')}. At 900 px and below \`.sec\` forces \`72px 20px\` (media query, section 7).\n`;
ui += `- **Grids** are inline \`grid-template-columns: repeat(N, minmax(0, 1fr))\` (\`.g2\`, \`.g3\`) and \`minmax(0,1fr) ×3 + minmax(0,1.25fr)\` for the four steps (\`.g4\`); all collapse to one column at 900 px and below.\n`;
ui += `- **Breakpoint**: one, \`max-width: 900px\` (768 and 390 use the same rules). Motion: \`prefers-reduced-motion: reduce\` stops the hero cross-fade and drift.\n\n`;

ui += `## 2. Section rhythm\n\n`;
for (const p of cfg.pages) {
  ui += `### ${p.name}\n\n| # | Element | id | Background | 1280: top · height · padding | 768: height | 390: height · padding |\n|---|---|---|---|---|---|---|\n`;
  R[p.name][1280].sections.forEach((s, i) => {
    const m = R[p.name][768].sections[i]; const n = R[p.name][390].sections[i];
    ui += `| ${i} | \`${s.tag}\` | ${s.id || ''} | ${hex(s.bg)} | ${s.rect[1]} · ${s.rect[3]} · ${s.pt}/${s.pb} | ${m?.rect[3] ?? ''} | ${n?.rect[3] ?? ''} · ${n?.pt}/${n?.pb} |\n`;
  });
  ui += `\nPage height: ${cfg.widths.map((w) => `${R[p.name][w].docH} px at ${w}`).join(', ')}.\n\n`;
}

ui += `## 3. Type scale\n\nText runs clustered by family, size, weight, style, tracking, leading, transform and colour (1280 px, both pages). "At 390" is the size of the same text at 390 px.\n\n| Family | Size 1280 | At 390 | Weight | Style | Tracking | Leading | Transform | Colour | Runs | Example |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
const clusters = new Map();
for (const p of cfg.pages) for (const t of R[p.name][1280].text) {
  const k = [t.ff, t.fs, t.fw, t.fst, t.ls, t.lh, t.tt, t.color].join('|');
  if (!clusters.has(k)) clusters.set(k, { t, n: 0, page: p.name }); clusters.get(k).n += 1;
}
for (const { t, n, page } of [...clusters.values()].sort((a, b) => parseFloat(b.t.fs) - parseFloat(a.t.fs) || b.n - a.n)) {
  const small = R[page][390].text.find((x) => norm(x.text) === norm(t.text));
  ui += `| ${t.ff} | ${t.fs} | ${small ? small.fs : 'hidden'} | ${t.fw} | ${t.fst} | ${t.ls} | ${t.lh} | ${t.tt} | ${hex(t.color)} | ${n} | ${cell(t.text.slice(0, 40))} |\n`;
}

ui += `\n## 4. Colours\n\n`;
const tc = {}; const bc = {};
for (const p of cfg.pages) { for (const t of R[p.name][1280].text) tc[hex(t.color)] = (tc[hex(t.color)] || 0) + 1; for (const b of R[p.name][1280].boxes) if (b.bg !== 'rgba(0, 0, 0, 0)') bc[hex(b.bg)] = (bc[hex(b.bg)] || 0) + 1; }
ui += `- **Text**: ${Object.entries(tc).sort((a, b) => b[1] - a[1]).map(([k, v]) => `\`${k}\` ×${v}`).join(', ')}.\n- **Fills**: ${Object.entries(bc).sort((a, b) => b[1] - a[1]).map(([k, v]) => `\`${k}\` ×${v}`).join(', ')}.\n- **Links**: \`#14161A\`, hover \`#2356C4\`; on dark \`#ECEAE4\`, hover \`#FFFFFF\`; focus ring \`2px solid #2356C4\`, offset 3 px (CSS, first rules).\n\n`;

ui += `## 5. Shell\n\nThe header sits inside the hero of each page (absolute on Main, in flow on Team); the footer is the last section. Both are part of the golden markup of each page.\n\n`;
for (const p of cfg.pages) {
  const runs = R[p.name][1280].text.filter((t) => t.rect[1] < 110);
  ui += `**${p.name}, header at 1280**: ${runs.map((t) => `"${cell(t.text)}" ${t.ff} ${t.fs}/${t.fw} at x ${t.rect[0]}`).join('; ')}. At 390 the links are hidden (\`.navlinks{display:none}\`), the two buttons stay.\n\n`;
  const f = R[p.name][1280].sections.at(-1);
  ui += `**${p.name}, footer**: top ${f.rect[1]}, height ${f.rect[3]} at 1280; ${R[p.name][390].sections.at(-1).rect[3]} at 390; background ${hex(f.bg)}.\n\n`;
}

ui += `## 6. Components (CSS classes)\n\nEvery class of \`spec/styles/<Page>.css\`, its rules and where it is used. The CSS is page-scoped by \`scripts/spec-css.mjs\` (\`[data-page="<Page>"] .class\`).\n\n| Class | Rules (first declaration) | Used in |\n|---|---|---|\n`;
const classRules = new Map();
for (const p of cfg.pages) for (const r of rules(css[p.name])) for (const s of r.selectors) for (const c of s.match(/\.[a-zA-Z][\w-]*/g) || []) {
  const k = c.slice(1); if (!classRules.has(k)) classRules.set(k, new Set());
  classRules.get(k).add(`${r.media ? r.media + ' ' : ''}\`${s}\` { ${r.decl.split(';')[0]} }${cfg.pages.length > 1 ? ` (${p.name})` : ''}`);
}
for (const [k, set] of [...classRules].sort()) {
  const used = cfg.pages.map((p) => { let n = 0; walk(rootOf(p.name), (x) => { if (isEl(x) && (attr(x, 'class') || '').split(/\s+/).includes(k)) n += 1; }); return n ? `${p.name} ×${n}` : null; }).filter(Boolean).join(', ') || 'states only';
  ui += `| \`.${k}\` | ${[...set].slice(0, 4).map(cell).join('<br>')} | ${used} |\n`;
}

ui += `\n## 7. Media queries\n\n`;
for (const p of cfg.pages) {
  const byMedia = {}; for (const r of rules(css[p.name]).filter((x) => x.media)) (byMedia[r.media] ||= []).push(`\`${r.selectors.join(', ')}\` { ${r.decl} }`);
  for (const [m, list] of Object.entries(byMedia)) ui += `**${p.name}, \`${m}\`**\n\n${list.map((x) => `- ${cell(x)}`).join('\n')}\n\n`;
}

ui += `## 8. Interactions\n\n| Page | Control | Label | Effect | State file | ARIA before → after |\n|---|---|---|---|---|---|\n`;
for (const c of beh.controls) ui += `| ${c.page} | \`${c.control}\` | ${cell(c.label)} | ${c.effect} | ${c.state ? `\`spec/${c.state}\`` : ''} | ${c.control === 'summary' ? `open ${c.ariaBefore.open} → ${c.ariaAfter.open}` : `aria-pressed ${c.ariaBefore.pressed} → ${c.ariaAfter.pressed}`} |\n`;
ui += `\nThe currency switch (€ Euro / £ Pound) is the only stateful control: it changes the two prices of section 5 (\`€149\` → \`£149\`, \`€2,500\` → \`£2,500\`) and \`aria-pressed\`. The design picks £ when the browser language is en-GB; the reference is € (en-US). The FAQ uses native \`<details>\`: it works without JavaScript.\n\n`;
ui += `## 9. Approved copy that differs from the design\n\n${overrides.map((o) => `- ${o.page}: "${o.use}" (${o.why})`).join('\n')}\n${seams.map((s) => `- ${s.page}: block removed, flag \`${s.flag}\`, kept in \`spec/${s.save}\` (${s.why})`).join('\n')}\n`;
fs.mkdirSync(path.join(ROOT, 'docs', 'pages'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'UI-SPEC.md'), ui);

// ---------------- Page sheets ----------------
for (const p of cfg.pages) {
  const r1 = R[p.name][1280]; const r3 = R[p.name][390];
  let md = head(`Page sheet: ${p.name} (\`${p.route}\`)`);
  md += `Title: ${p.title}. Golden markup \`spec/markup/${p.name}.html\`; references \`spec/reference/${p.name}-1280.png\` and \`-390.png\`; redlines \`spec/redlines/${p.name}.<width>.json\`. Generate the page with \`pnpm port spec/markup/${p.name}.html <out.tsx> ${p.name}Page\`.\n\n`;
  md += `## Section map\n\n| # | Element | id | Background | Top · height at 1280 | Top · height at 390 | Classes |\n|---|---|---|---|---|---|---|\n`;
  const secs = sectionsOf(p.name);
  r1.sections.forEach((s, i) => { md += `| ${i} | \`${s.tag}\` | ${s.id || ''} | ${hex(s.bg)} | ${s.rect[1]} · ${s.rect[3]} | ${r3.sections[i].rect[1]} · ${r3.sections[i].rect[3]} | ${(attr(secs[i], 'class') || '').split(' ').filter(Boolean).map((c) => `\`${c}\``).join(' ')} |\n`; });
  r1.sections.forEach((s, i) => {
    const node = secs[i];
    const heads = []; const ls = []; walk(node, (n) => { if (!isEl(n)) return; if (/^h[1-4]$/.test(n.tagName)) heads.push(`${n.tagName}: "${norm(textOf(n)) ? textOf(n).replace(/\s+/g, ' ').trim() : ''}"`); if (n.tagName === 'a') ls.push(`"${textOf(n).replace(/\s+/g, ' ').trim()}" → \`${linkTarget(p.name, textOf(n), attr(n, 'href') || '', links, routeOf)}\``); });
    const ctrls = beh.controls.filter((c) => c.page === p.name && c.sectionIndex === i);
    const runs = r1.text.filter((t) => t.rect[1] >= s.rect[1] && t.rect[1] < s.rect[1] + s.rect[3]);
    md += `\n## Section ${i}: ${cell(s.text.slice(0, 50))}\n\n`;
    if (heads.length) md += `- **Headings**: ${heads.map(cell).join('; ')}\n`;
    md += `- **Classes used**: ${classesIn(node).map((c) => `\`.${c}\``).join(' ') || 'none (inline styles only)'}\n`;
    if (ls.length) md += `- **Links**: ${ls.map(cell).join('; ')}\n`;
    if (ctrls.length) md += `- **Controls**: ${ctrls.map((c) => `${c.control} "${cell(c.label)}"${c.state ? ` → \`spec/${c.state}\`` : ' (no change)'}`).join('; ')}\n`;
    md += `- **Copy, verbatim** (text runs in order, with family/size/weight at 1280):\n\n`;
    for (const t of runs) md += `  - ${cell(t.text)} *(${t.ff} ${t.fs}/${t.fw}${t.fst === 'italic' ? ' italic' : ''}${t.tt !== 'none' ? ' ' + t.tt : ''})*\n`;
  });
  fs.writeFileSync(path.join(ROOT, 'docs', 'pages', `${p.name}.md`), md);
}
