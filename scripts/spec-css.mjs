// Generate the site's CSS and static files from the frozen spec. Never edit the outputs by hand.
//   node scripts/spec-css.mjs                  -> app/spec.css, public/fonts/*, public/images/*
//   node scripts/spec-css.mjs --out <dir>      -> <dir>/spec.css, <dir>/fonts/*, <dir>/images/* (golden site)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SPEC, readJSON, pagesConfig, scopeCss } from './conformity/lib.mjs';

const outArg = process.argv.indexOf('--out');
const outDir = outArg > -1 ? path.resolve(process.argv[outArg + 1]) : null;
const cssFile = outDir ? path.join(outDir, 'spec.css') : path.join(ROOT, 'app', 'spec.css');
const publicDir = outDir || path.join(ROOT, 'public');

const cfg = pagesConfig();
let css = `/* GENERATED by scripts/spec-css.mjs from spec/styles/*.css. Do not edit: change spec/ (docs/CONFORMITY.md section 7). */\n`;
css += fs.readFileSync(path.join(SPEC, 'styles', 'fonts.css'), 'utf8') + '\n';
for (const p of cfg.pages) {
  css += `/* ---- ${p.name} (spec/styles/${p.name}.css, scoped) ---- */\n`;
  css += scopeCss(fs.readFileSync(path.join(SPEC, 'styles', `${p.name}.css`), 'utf8'), p.name) + '\n';
}
fs.mkdirSync(path.dirname(cssFile), { recursive: true });
fs.writeFileSync(cssFile, css);

for (const [sub, from] of [['fonts', 'fonts'], ['images', 'assets']]) {
  const dst = path.join(publicDir, sub); fs.mkdirSync(dst, { recursive: true });
  for (const f of fs.readdirSync(path.join(SPEC, from))) fs.copyFileSync(path.join(SPEC, from, f), path.join(dst, f));
}
console.log(`wrote ${path.relative(ROOT, cssFile) || cssFile} (${css.length} bytes), fonts and images to ${path.relative(ROOT, publicDir) || publicDir}`);
