// spec-css.mjs — builds app/spec.css from the frozen CSS of the reference. Never edit the output.
import fs from 'node:fs';
const parts = ['base.css', 'ui.css', 'logos.css'].map(f => `/* spec/styles/${f} */\n` + fs.readFileSync(`spec/styles/${f}`, 'utf8'));
fs.mkdirSync('app', { recursive: true });
fs.writeFileSync('app/spec.css', '/* GENERATED by scripts/spec-css.mjs from spec/styles. Do not edit. */\n' + parts.join('\n'));
console.log('app/spec.css written');
